import { test, expect, type Page } from "@playwright/test";
test.skip(
  process.env.RUN_DEMO_LOGIN !== "true",
  "Requires the separate local demo server.",
);

async function login(page: Page, username: string, checkFailure = false) {
  await page.goto("/doctor");
  await expect(page.getByText(/Sample hospital demonstration/)).toBeVisible();
  await page.getByRole("link", { name: "Sign in with organization" }).click();
  await expect(
    page.getByRole("heading", { name: /Sample Hospital.*Doctor sign-in/ }),
  ).toBeVisible();
  await page.getByLabel("Email", { exact: true }).fill(username);
  await page
    .getByLabel("Password", { exact: true })
    .fill(checkFailure ? "incorrect" : "DemoDoctor!2026");
  await page
    .getByLabel("Demo verification code", { exact: true })
    .fill("123456");
  await page
    .getByRole("button", { name: "Sign in to Sample Hospital" })
    .click();
  if (checkFailure) {
    await expect(page.getByRole("alert")).toContainText("incorrect");
    await expect(page.getByLabel("Email", { exact: true })).toHaveValue(
      username,
    );
    await page.getByLabel("Email", { exact: true }).fill(username);
    await page.getByLabel("Password", { exact: true }).fill("DemoDoctor!2026");
    await page
      .getByLabel("Demo verification code", { exact: true })
      .fill("123456");
    await page
      .getByRole("button", { name: "Sign in to Sample Hospital" })
      .click();
  }
  await page.waitForURL("**/practice");
  await expect(page.getByRole("button", { name: /Alex Tan/ })).toBeVisible();
}

test("reviewer completes real OIDC login, sees seeded records and can sign out", async ({
  page,
}) => {
  await login(page, "reviewer@demo.local", true);
  await expect(
    page.getByRole("heading", { name: "Dr Maya Chen" }),
  ).toBeVisible();
  await expect(page.getByRole("button", { name: /Priya Kumar/ })).toBeVisible();
  await page.getByRole("button", { name: /Alex Tan/ }).click();
  await expect(
    page.getByRole("button", { name: "Review & approve", exact: true }),
  ).toBeVisible();
  await page.getByRole("button", { name: "AI summaries", exact: true }).click();
  await expect(
    page.getByText(/Synthetic fixture · not generated by a live AI model/),
  ).toBeVisible();
  await page.getByRole("button", { name: "Documents", exact: true }).click();
  const url = await page
    .getByRole("link", { name: "Download", exact: true })
    .getAttribute("href");
  const document = await page.request.get(url!);
  expect(document.status()).toBe(200);
  expect(await document.text()).toContain("No real patient information");
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  expect((await page.request.get("/api/practice/bootstrap")).status()).toBe(
    401,
  );
});

test("editing doctor and patient view-only doctor receive distinct permissions", async ({
  browser,
}) => {
  for (const [username, canWrite] of [
    ["doctor@demo.local", true],
    ["viewer@demo.local", false],
  ] as const) {
    const context = await browser.newContext({
      baseURL: process.env.TEST_BASE_URL || "http://127.0.0.1:3109",
    });
    const page = await context.newPage();
    await login(page, username, canWrite);
    const directory = await (
      await page.request.get("/api/practice/bootstrap")
    ).json();
    const patient = directory.patients.find(
      (item: { identifier: string }) => item.identifier === "SYN-1001",
    );
    const detail = await (
      await page.request.get(`/api/practice/patients/${patient.id}`)
    ).json();
    expect(detail.permissions).toEqual({
      canWrite,
      canApprove: false,
      canManage: false,
    });
    await page.getByRole("button", { name: /Alex Tan/ }).click();
    if (canWrite)
      await expect(
        page.getByRole("button", { name: "Save for review", exact: true }),
      ).toBeVisible();
    else {
      await expect(page.getByText("View only", { exact: true })).toBeVisible();
      await expect(
        page.getByRole("button", { name: "Save for review", exact: true }),
      ).toHaveCount(0);
      const denied = await page.request.post(
        `/api/practice/patients/${patient.id}/notes`,
        {
          headers: { Origin: new URL(page.url()).origin },
          data: { text: "Denied synthetic write" },
        },
      );
      expect(denied.status()).toBe(403);
    }
    await context.close();
  }
});

test("sample identity rejects invalid redirects and unauthenticated token requests", async ({
  request,
}) => {
  const response = await request.get(
    "http://127.0.0.1:4111/authorize?client_id=noticioner-local-demo&redirect_uri=https://external.example/callback",
  );
  expect(response.status()).toBe(400);
  expect(
    (
      await request.post("http://127.0.0.1:4111/token", {
        form: {
          code: "fake",
          client_id: "noticioner-local-demo",
          client_secret: "incorrect",
        },
      })
    ).status(),
  ).toBe(401);
});
